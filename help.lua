local function VNMJIDG_fake_script() -- ScreenGui.LocalScript 
	local script = Instance.new('LocalScript', ScreenGui)

	local UIS = game:GetService("UserInputService")
	local gui = script.Parent
	
	local active
	local drag
	
	local function start(obj, input)
		drag = {start = input.Position, pos = obj.Position}
		active = obj
	end
	
	local function stop()
		active = nil
		drag = nil
	end
	
	UIS.InputChanged:Connect(function(input)
		if not active or not drag then return end
		if input.UserInputType ~= Enum.UserInputType.MouseMovement
			and input.UserInputType ~= Enum.UserInputType.Touch then return end
		local delta = input.Position - drag.start
		active.Position = UDim2.new(
			drag.pos.X.Scale, drag.pos.X.Offset + delta.X,
			drag.pos.Y.Scale, drag.pos.Y.Offset + delta.Y
		)
	end)
	
	UIS.InputEnded:Connect(function(input)
		if input.UserInputType == Enum.UserInputType.MouseButton1
			or input.UserInputType == Enum.UserInputType.Touch then
			stop()
		end
	end)
	
	for _, v in gui:GetChildren() do
		if not v:IsA("GuiObject") then continue end
		v.Active = true
		v.InputBegan:Connect(function(input)
			if input.UserInputType == Enum.UserInputType.MouseButton1
				or input.UserInputType == Enum.UserInputType.Touch then
				start(v, input)
			end
		end)
	end
end
