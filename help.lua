		local r = character:FindFirstChild("RightLowerArm") or character:FindFirstChild("Right Arm")
		if l then table.insert(arms, l) end
		if r then table.insert(arms, r) end
		return arms
	end
	
	local function setAnchor(character, state)
		local parts = {}
		for _, v in character:GetDescendants() do
			if v:IsA("BasePart") then
				table.insert(parts, v)
			end
		end
		for i = 1, #parts, 50 do
			local chunk = {}
			for j = i, math.min(i + 49, #parts) do
				table.insert(chunk, {Part = parts[j], Anchored = state})
			end
			fire("SyncAnchor", chunk)
			task.wait()
		end
	end
	
	local function releaseCuff(character)
		local entry = cuffed[character]
		if not entry then return end
		cuffed[character] = nil
		for _, p in entry.parts do
			fire("Remove", {p})
		end
		for _, w in entry.welds do
			fire("Remove", {w})
		end
		setAnchor(character, false)
	end
	
	local function cuffPlayer(character)
		if cuffed[character] then
			releaseCuff(character)
			return
		end
		local arms = findArms(character)
		if #arms == 0 then return end
		setAnchor(character, true)
		local parts, welds = {}, {}
		for _, arm in arms do
			local p = buildCuff(arm.CFrame, character)
			if p then
				table.insert(parts, p)
				local ok, made = fire("CreateWelds", {p}, arm)
				if ok and made then
					for _, w in made do
						table.insert(welds, w)
					end
				end
			end
		end
		cuffed[character] = {parts = parts, welds = welds}
	end
	
	local function makeTool(c)
		if tool then tool:Destroy() end
		heldCuff = nil
		tool = Instance.new("Tool")
		tool.Name = "Handcuffs"
		tool.RequiresHandle = true
		tool.CanBeDropped = false
		local handle = Instance.new("Part")
		handle.Name = "Handle"
		handle.Size = Vector3.new(0.2, 0.2, 0.2)
		handle.Transparency = 1
		handle.CanCollide = false
		handle.Massless = true
		handle.Parent = tool
		tool.Parent = c
	
		tool.Equipped:Connect(function()
			local hand = c:FindFirstChild("RightHand") or c:FindFirstChild("Right Arm")
			if hand and not heldCuff then
				heldCuff = buildCuff(hand.CFrame, c)
			end
		end)
	
		tool.Unequipped:Connect(function()
			if heldCuff then
				fire("Remove", {heldCuff})
				heldCuff = nil
			end
		end)
	end
	
	makeTool(char)
	
	lp.CharacterAdded:Connect(function(c)
		char = c
		cuffed = {}
		task.wait(0.5)
		makeTool(c)
	end)
	
	local acc = 0
	RunService.Heartbeat:Connect(function(dt)
		acc += dt
		if acc < 1 / SYNC_HZ then return end
		acc = 0
		if not tool or tool.Parent ~= char then return end
		local root = char:FindFirstChild("HumanoidRootPart")
		if not root then return end
	
		local moves = {}
		if heldCuff and heldCuff.Parent then
			local hand = char:FindFirstChild("RightHand") or char:FindFirstChild("Right Arm")
			if hand then
				table.insert(moves, {Part = heldCuff, CFrame = hand.CFrame})
			end
		end
	
		local i = 0
		for model in cuffed do
			if model.Parent and model:FindFirstChildOfClass("Humanoid") then
				i += 1
				local held = root.CFrame * CFrame.new((i - 1) * 2.4, 0, -HOLD_GAP)
				table.insert(moves, {Model = model, Pivot = held})
			end
		end
	
		if #moves == 0 then return end
		for j = 1, #moves, 50 do
			local chunk = {}
			for k = j, math.min(j + 49, #moves) do
				table.insert(chunk, moves[k])
			end
			fire("SyncMove", chunk)
		end
	end)
	
	btn.MouseButton1Click:Connect(function()
		local hum = char:FindFirstChildOfClass("Humanoid")
		if not hum or not tool then return end
		if tool.Parent == char then
			hum:UnequipTools()
		else
			hum:EquipTool(tool)
		end
	end)
	
	UIS.InputBegan:Connect(function(input, processed)
		if processed then return end
		if input.UserInputType ~= Enum.UserInputType.MouseButton1 then return end
		if not tool or tool.Parent ~= char then return end
		local target = lp:GetMouse().Target
		if not target then return end
		local model = target:FindFirstAncestorOfClass("Model")
		if not model or model == char then return end
		if not model:FindFirstChildOfClass("Humanoid") then return end
		cuffPlayer(model)
	end)
end
